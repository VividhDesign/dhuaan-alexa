// Embeds the built Echo Show card and the legal pages into src/generated/assets.ts (run before build/test).
import { readFileSync, writeFileSync } from "node:fs";
const r = (p) => readFileSync(new URL(p, import.meta.url), "utf-8");
const out = `// Generated by scripts/embed.mjs. Do not edit.
export const CARD_HTML = ${JSON.stringify(r("../../ui/dist/forecast-card.html"))};
export const PRIVACY_HTML = ${JSON.stringify(r("../src/pages/privacy.html"))};
export const TERMS_HTML = ${JSON.stringify(r("../src/pages/terms.html"))};
`;
writeFileSync(new URL("../src/generated/assets.ts", import.meta.url), out);
console.log(`embedded card ${(out.length / 1024).toFixed(0)} KB`);
